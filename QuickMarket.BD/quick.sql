  CREATE OR REPLACE EDITIONABLE TRIGGER "QUICKMARKET_USER"."TRG_DETALLE_STOCK_BI" 
BEFORE INSERT OR UPDATE OF CANTIDAD, PRECIO_UNITARIO, ID_PRODUCTO ON DETALLE_VENTAS
FOR EACH ROW
DECLARE
  v_stock NUMBER;
BEGIN
  IF INSERTING THEN
    IF :NEW.CANTIDAD <= 0 THEN
      RAISE_APPLICATION_ERROR(-20001, 'Cantidad debe ser > 0');
    END IF;

    SELECT STOCK INTO v_stock
      FROM PRODUCTOS
     WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
     FOR UPDATE;

    IF v_stock < :NEW.CANTIDAD THEN
      RAISE_APPLICATION_ERROR(-20002, 'Stock insuficiente');
    END IF;

    UPDATE PRODUCTOS
       SET STOCK = STOCK - :NEW.CANTIDAD
     WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

  ELSIF UPDATING THEN
    IF :OLD.ID_PRODUCTO <> :NEW.ID_PRODUCTO THEN
      -- Regresa cantidad al producto anterior
      UPDATE PRODUCTOS
         SET STOCK = STOCK + :OLD.CANTIDAD
       WHERE ID_PRODUCTO = :OLD.ID_PRODUCTO;

      -- Descuenta en el nuevo producto
      SELECT STOCK INTO v_stock
        FROM PRODUCTOS
       WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
       FOR UPDATE;

      IF :NEW.CANTIDAD <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Cantidad debe ser > 0');
      END IF;

      IF v_stock < :NEW.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20002, 'Stock insuficiente para el nuevo producto');
      END IF;

      UPDATE PRODUCTOS
         SET STOCK = STOCK - :NEW.CANTIDAD
       WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    ELSE
      -- Mismo producto: ajusta por diferencia
      UPDATE PRODUCTOS
         SET STOCK = STOCK + :OLD.CANTIDAD - :NEW.CANTIDAD
       WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

      SELECT STOCK INTO v_stock
        FROM PRODUCTOS
       WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

      IF v_stock < 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Stock insuficiente al actualizar');
      END IF;
    END IF;
  END IF;
END;

