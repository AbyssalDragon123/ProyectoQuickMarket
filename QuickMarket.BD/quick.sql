--  DDL for Trigger TRG_VENTAS_RECALC
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "QUICKMARKET_USER"."TRG_VENTAS_RECALC" 
FOR INSERT OR UPDATE OR DELETE ON DETALLE_VENTAS
COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  g_ids t_ids;

  PROCEDURE add_id(p_id NUMBER) IS
  BEGIN
    IF p_id IS NOT NULL THEN
      FOR i IN 1 .. g_ids.COUNT LOOP
        IF g_ids(i) = p_id THEN RETURN; END IF;
      END LOOP;
      g_ids(g_ids.COUNT + 1) := p_id;
    END IF;
  END;

  AFTER EACH ROW IS
  BEGIN
    IF INSERTING OR UPDATING THEN
      add_id(:NEW.ID_VENTA);
    ELSIF DELETING THEN
      add_id(:OLD.ID_VENTA);
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_tasa CONSTANT NUMBER := 0.12;
  BEGIN
    FOR i IN 1 .. g_ids.COUNT LOOP
      UPDATE VENTAS v
         SET (TOTAL_BRUTO, TOTAL_IMPUESTOS, TOTAL_NETO) = (
               SELECT NVL(SUM(d.SUBTOTAL), 0),
                      ROUND(NVL(SUM(d.SUBTOTAL), 0) * v_tasa, 2),
                      NVL(SUM(d.SUBTOTAL), 0) + ROUND(NVL(SUM(d.SUBTOTAL), 0) * v_tasa, 2)
                 FROM DETALLE_VENTAS d
                WHERE d.ID_VENTA = v.ID_VENTA
             )
       WHERE v.ID_VENTA = g_ids(i);
    END LOOP;
  END AFTER STATEMENT;
END TRG_VENTAS_RECALC;

