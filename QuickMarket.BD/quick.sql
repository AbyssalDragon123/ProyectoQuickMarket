--  DDL for Procedure SP_CREAR_VENTA
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "QUICKMARKET_USER"."SP_CREAR_VENTA" (
  p_id_cliente IN NUMBER,
  p_items_json IN CLOB,   -- Ej: '[{"id_producto":1,"cantidad":2},{"id_producto":2,"cantidad":3}]'
  p_id_venta   OUT NUMBER
) IS
  v_id_venta  NUMBER;
  v_items_cnt NUMBER := 0;
BEGIN
  -- 0) Validación mínima de entrada
  IF p_id_cliente IS NULL THEN
    RAISE_APPLICATION_ERROR(-20040, 'Debe indicar p_id_cliente.');
  END IF;
  IF p_items_json IS NULL OR DBMS_LOB.getlength(p_items_json) = 0 THEN
    RAISE_APPLICATION_ERROR(-20041, 'Debe enviar p_items_json con al menos un item.');
  END IF;

  -- 1) Crear encabezado de venta
  INSERT INTO VENTAS (ID_CLIENTE)
  VALUES (p_id_cliente)
  RETURNING ID_VENTA INTO v_id_venta;

  -- 2) Insertar detalles desde el JSON
  FOR r IN (
    SELECT
      jt.id_producto,
      jt.cantidad,
      COALESCE(
        jt.precio_unitario,
        (SELECT PRECIO_UNITARIO
           FROM PRODUCTOS
          WHERE ID_PRODUCTO = jt.id_producto)
      ) AS precio_unitario
    FROM JSON_TABLE(
           p_items_json, '$[*]'
           COLUMNS (
             id_producto     NUMBER PATH '$.id_producto',
             cantidad        NUMBER PATH '$.cantidad',
             precio_unitario NUMBER PATH '$.precio_unitario' NULL ON ERROR
           )
         ) jt
  ) LOOP
    -- Validación por ítem
    IF r.id_producto IS NULL THEN
      RAISE_APPLICATION_ERROR(-20050, 'Item inválido: id_producto es NULL.');
    END IF;
    IF r.cantidad IS NULL OR r.cantidad <= 0 THEN
      RAISE_APPLICATION_ERROR(-20051, 'Item inválido: cantidad debe ser > 0.');
    END IF;
    IF r.precio_unitario IS NULL OR r.precio_unitario < 0 THEN
      RAISE_APPLICATION_ERROR(-20052, 'Item inválido: precio_unitario no disponible o negativo.');
    END IF;

    INSERT INTO DETALLE_VENTAS (ID_VENTA, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO)
    VALUES (v_id_venta, r.id_producto, r.cantidad, r.precio_unitario);

    v_items_cnt := v_items_cnt + 1;
  END LOOP;

  -- 3) Asegura que hubo al menos un detalle
  IF v_items_cnt = 0 THEN
    RAISE_APPLICATION_ERROR(-20053, 'La venta no tiene ítems (JSON vacío o mal formado).');
  END IF;

  -- 4) Devolver ID generado
  p_id_venta := v_id_venta;

  -- Nota: no hacemos COMMIT aquí a propósito (mejor práctica).
EXCEPTION
  WHEN OTHERS THEN
    -- Si quieres deshacer aquí mismo, descomenta:
    -- ROLLBACK;
    RAISE;
END;

